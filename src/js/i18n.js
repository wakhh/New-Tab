// ====== 环境常量 ======
export const isBrowserZh = (typeof navigator !== 'undefined' && /zh/i.test(navigator.language))

// ====== 语言解析 ======
function resolveLang(pref) {
  if (pref === 'zh' || pref === 'en') return pref
  return isBrowserZh ? 'zh' : 'en'
}

export const t = (key) => dict[resolveLang(langPref.value)]?.[key] ?? key
export { resolveLang }